#!/usr/bin/env python3
"""
COMP9085 - Machine Learning and Foundation Models for Biology, Healthcare and Nutrition
Build script 01: export the REAL UCI Breast Cancer Wisconsin (Diagnostic) dataset
into a browser-loadable JavaScript file.

PROVENANCE
----------
Source     : UCI Machine Learning Repository, "Breast Cancer Wisconsin (Diagnostic)"
             Wolberg, W., Mangasarian, O., Street, N. & Street, W. (1993).
             DOI: 10.24432/C5DW2B
Access     : bundled with scikit-learn as sklearn.datasets.load_breast_cancer
Licence    : CC BY 4.0
Instances  : 569
Features   : 30 real-valued (10 nuclear measurements x mean / SE / worst)
Target     : diagnosis, 357 benign / 212 malignant

This is REAL measured data. Nothing here is synthetic.

Run:  python3 data/scripts/01_build_wdbc.py
Out:  js/data/wdbc.js
"""
import json
import os

import numpy as np
from sklearn.datasets import load_breast_cancer

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "js", "data", "wdbc.js")

SHORT = {
    "mean radius": "radius_mean", "mean texture": "texture_mean",
    "mean perimeter": "perimeter_mean", "mean area": "area_mean",
    "mean smoothness": "smoothness_mean", "mean compactness": "compactness_mean",
    "mean concavity": "concavity_mean", "mean concave points": "concave_points_mean",
    "mean symmetry": "symmetry_mean", "mean fractal dimension": "fractal_dim_mean",
    "radius error": "radius_se", "texture error": "texture_se",
    "perimeter error": "perimeter_se", "area error": "area_se",
    "smoothness error": "smoothness_se", "compactness error": "compactness_se",
    "concavity error": "concavity_se", "concave points error": "concave_points_se",
    "symmetry error": "symmetry_se", "fractal dimension error": "fractal_dim_se",
    "worst radius": "radius_worst", "worst texture": "texture_worst",
    "worst perimeter": "perimeter_worst", "worst area": "area_worst",
    "worst smoothness": "smoothness_worst", "worst compactness": "compactness_worst",
    "worst concavity": "concavity_worst", "worst concave points": "concave_points_worst",
    "worst symmetry": "symmetry_worst", "worst fractal dimension": "fractal_dim_worst",
}

# Biological meaning of the ten base nuclear measurements, from the UCI
# dataset documentation (Street, Wolberg & Mangasarian, 1993).
MEANING = {
    "radius": "Mean distance from the nucleus centre to points on its perimeter. Larger, swollen nuclei are associated with malignancy.",
    "texture": "Standard deviation of grey-scale values inside the nucleus. Coarse chromatin texture is a classical malignancy marker.",
    "perimeter": "Length of the traced nuclear boundary.",
    "area": "Number of pixels inside the nuclear boundary, with half the perimeter pixels added.",
    "smoothness": "Local variation in radius lengths. Irregular boundaries suggest disordered growth.",
    "compactness": "perimeter^2 / area - 1.0. High values indicate an irregular, non-circular nucleus.",
    "concavity": "Severity of concave portions of the nuclear contour, i.e. how deeply the boundary is indented.",
    "concave points": "Number of concave portions of the contour, as opposed to their severity.",
    "symmetry": "Difference in length between the two halves of the nucleus about its major axis.",
    "fractal dimension": "Coastline approximation minus 1: how much the boundary length grows as measurement scale shrinks.",
}


def main():
    d = load_breast_cancer()
    names = [SHORT[n] for n in d.feature_names]
    X = np.round(d.data, 6)
    # scikit-learn encodes 0 = malignant, 1 = benign. Present the clinical label.
    labels = [str(d.target_names[t]) for t in d.target]

    payload = {
        "id": "wdbc",
        "name": "Breast Cancer Wisconsin (Diagnostic)",
        "real": True,
        "provenance": ("UCI Machine Learning Repository (DOI 10.24432/C5DW2B), "
                       "distributed with scikit-learn. Real measured data."),
        "licence": "CC BY 4.0",
        "n": int(X.shape[0]),
        "features": names,
        "featureMeaning": MEANING,
        "target": "diagnosis",
        "classes": ["benign", "malignant"],
        "classCounts": {"benign": labels.count("benign"),
                        "malignant": labels.count("malignant")},
        "X": [[float(v) for v in row] for row in X],
        "y": labels,
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("/* AUTO-GENERATED by data/scripts/01_build_wdbc.py - do not edit by hand.\n")
        f.write("   REAL DATA: UCI Breast Cancer Wisconsin (Diagnostic), CC BY 4.0. */\n")
        f.write("window.WDBC = ")
        json.dump(payload, f, separators=(",", ":"))
        f.write(";\n")
    print("wrote", OUT, payload["n"], "x", len(names), payload["classCounts"])


if __name__ == "__main__":
    main()
