#!/usr/bin/env python3
"""
COMP9085 build script 03: protein-sequence teaching set + embeddings.

READ THIS BEFORE TEACHING FROM THE OUTPUT
-----------------------------------------
The sequences produced here are SIMULATED, not real proteins. They are drawn
from hand-specified position-weight matrices so that four "families" have
different conserved motifs, different length distributions and different
amino-acid usage. They exist so that students can explore the geometry of a
representation space in the browser without downloading gigabytes of weights.

What is genuinely computed from those sequences:
  * amino-acid composition (20 dimensions)
  * Kyte-Doolittle GRAVY hydropathy, using the published 1982 scale
  * net charge at pH 7, molecular weight, aromaticity, sequence length
  These are real calculations applied to the simulated sequences.

What is SIMULATED and labelled as such everywhere it is used:
  * the 320-dimensional "protein language model" embedding. It is generated by
    a documented process (family centroid + shared anisotropic background +
    per-sequence noise correlated with the real biophysical features) chosen so
    that it behaves qualitatively like a protein language model embedding
    space: high-dimensional, dominated by a few directions, class structure
    present but not perfectly separable, and richer than composition alone.
    It is NOT the output of ESM-2, ProtT5 or any other model.

HOW TO REPLACE THE SIMULATION WITH REAL ESM-2 EMBEDDINGS
--------------------------------------------------------
Script 04 (data/scripts/04_real_esm2_embeddings.py) does exactly that. It needs
internet access and about 100 MB of downloads. Run it and it overwrites the
embedding block in js/data/sequences.js, flipping the `simulatedEmbedding` flag
to false. The website reads that flag and changes its own banners accordingly,
so the teaching material stays truthful either way.

Run:  python3 data/scripts/03_build_sequences.py
Out:  js/data/sequences.js
"""
