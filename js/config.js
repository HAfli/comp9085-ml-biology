/* ---------------------------------------------------------------------------
 * Helpers used across the site. Kept here so that config semantics live with
 * the config.
 * ------------------------------------------------------------------------ */
window.SITE_CONFIG.getLink = function (key) {
  var l = window.SITE_CONFIG.links[key];
  if (!l) return null;
  return (l.status === 'confirmed' && l.url) ? l : null;
};

window.SITE_CONFIG.getVideo = function (key) {
  var v = window.SITE_CONFIG.youtube[key];
  if (!v) return null;
  return v;
};

window.SITE_CONFIG.slidePath = function (week, ext) {
  var nn = week < 10 ? '0' + week : String(week);
  return window.SITE_CONFIG.slides.base +
    window.SITE_CONFIG.slides.pattern.replace(/\{NN\}/g, nn) + '.' + ext;
};

window.SITE_CONFIG.hasLab = function (week) {
  return window.SITE_CONFIG.features.weeksWithoutLab.indexOf(week) === -1;
};
